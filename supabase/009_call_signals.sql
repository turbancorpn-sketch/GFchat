-- GFchat/Scooter: WebRTC call signaling (SDP offer/answer + ICE candidates)
-- between the two couple members. Rides the same Realtime pipeline already
-- used for messages — no separate signaling server needed.

create table if not exists public.call_signals (
  id bigint generated by default as identity primary key,
  couple_id uuid not null references public.couples(id) on delete cascade,
  sender_id uuid not null,
  kind text not null check (kind in ('offer','answer','ice','end','reject','busy')),
  payload text not null,
  created_at timestamptz not null default now()
);

alter table public.call_signals enable row level security;

drop policy if exists call_signals_select_own_couple on public.call_signals;
create policy call_signals_select_own_couple
  on public.call_signals
  for select
  to authenticated
  using (couple_id = private_my_couple_id());

grant select on public.call_signals to authenticated;

alter publication supabase_realtime add table public.call_signals;

create or replace function public.send_call_signal(kind text, payload text)
returns bigint
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  cid uuid := private_my_couple_id();
  new_id bigint;
begin
  if kind not in ('offer','answer','ice','end','reject','busy') then raise exception 'INVALID_KIND'; end if;
  insert into public.call_signals (couple_id, sender_id, kind, payload)
    values (cid, uid, kind, payload) returning id into new_id;
  return new_id;
end;
$$;

-- since = pichhli baar dekha hua timestamp (null = bas pichhle 1 minute ke signals,
-- taaki ghanton purana atka hua "offer" achanak incoming-call na dikha de).
create or replace function public.fetch_call_signals(since text default null)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  cid uuid := private_my_couple_id();
  since_ts timestamptz := coalesce(since::timestamptz, now() - interval '1 minute');
  result jsonb;
begin
  select coalesce(jsonb_agg(jsonb_build_object(
    'id', s.id, 'kind', s.kind, 'payload', s.payload, 'created_at', s.created_at
  ) order by s.created_at, s.id), '[]'::jsonb)
  into result
  from public.call_signals s
  where s.couple_id = cid and s.sender_id <> uid and s.created_at > since_ts;

  -- purane signals saaf karte raho (5 minute se zyada purane)
  delete from public.call_signals where couple_id = cid and created_at < now() - interval '5 minutes';

  return result;
end;
$$;

revoke all on function public.send_call_signal(text, text) from public, anon;
revoke all on function public.fetch_call_signals(text) from public, anon;
grant execute on function public.send_call_signal(text, text) to authenticated;
grant execute on function public.fetch_call_signals(text) to authenticated;
