-- GFchat/Closer: real messaging with sent/delivered/read ticks.
-- Supabase Dashboard -> SQL Editor me paste karke Run karo (001, 002, 003 ke baad).

create table if not exists public.messages (
  id bigint generated by default as identity primary key,
  couple_id uuid not null references public.couples (id) on delete cascade,
  sender_id uuid not null references auth.users (id) on delete cascade,
  kind text not null default 'text' check (kind in ('text', 'photo', 'video')),
  body text,
  created_at timestamptz not null default now(),
  delivered_at timestamptz,
  read_at timestamptz
);

create index if not exists messages_couple_id_idx on public.messages (couple_id, id);

alter table public.messages enable row level security;
-- Koi direct table policy nahi: sab kuch neeche ke security-definer functions se hota hai,
-- taaki sirf apne couple ke messages hi bheje/padhe ja sakein.

-- Caller ka couple id (sirf paired ho to milta hai).
create or replace function private_my_couple_id()
returns uuid
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  cid uuid;
begin
  if uid is null then raise exception 'NOT_AUTHENTICATED'; end if;
  select id into cid from public.couples where (user_a = uid or user_b = uid) and user_b is not null;
  if cid is null then raise exception 'NOT_PAIRED'; end if;
  return cid;
end;
$$;

create or replace function public.send_message(kind text, body text)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  cid uuid := private_my_couple_id();
  row public.messages;
begin
  if kind not in ('text', 'photo', 'video') then raise exception 'INVALID_KIND'; end if;
  if kind = 'text' and coalesce(trim(body), '') = '' then raise exception 'EMPTY_MESSAGE'; end if;

  insert into public.messages (couple_id, sender_id, kind, body)
    values (cid, uid, kind, body)
    returning * into row;

  return jsonb_build_object(
    'id', row.id, 'kind', row.kind, 'body', row.body,
    'created_at', row.created_at, 'delivered_at', row.delivered_at, 'read_at', row.read_at,
    'from_me', true
  );
end;
$$;

-- Naye messages laata hai (after_id se aage) aur saath me unhe "delivered" mark kar deta hai.
create or replace function public.fetch_messages(after_id bigint default 0)
returns jsonb
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  cid uuid := private_my_couple_id();
begin
  update public.messages
    set delivered_at = now()
    where couple_id = cid and sender_id <> uid and delivered_at is null;

  return coalesce((
    select jsonb_agg(jsonb_build_object(
      'id', m.id, 'kind', m.kind, 'body', m.body,
      'created_at', m.created_at, 'delivered_at', m.delivered_at, 'read_at', m.read_at,
      'from_me', (m.sender_id = uid)
    ) order by m.id)
    from public.messages m
    where m.couple_id = cid and m.id > after_id
  ), '[]'::jsonb);
end;
$$;

-- Chat screen khuli ho to isse call karo: partner ke bheje messages "read" mark ho jaate hain.
create or replace function public.mark_read()
returns void
language plpgsql
security definer
set search_path = public
as $$
declare
  uid uuid := auth.uid();
  cid uuid := private_my_couple_id();
begin
  update public.messages
    set read_at = now(), delivered_at = coalesce(delivered_at, now())
    where couple_id = cid and sender_id <> uid and read_at is null;
end;
$$;

revoke all on function public.send_message(text, text) from public, anon;
revoke all on function public.fetch_messages(bigint) from public, anon;
revoke all on function public.mark_read() from public, anon;
grant execute on function public.send_message(text, text) to authenticated;
grant execute on function public.fetch_messages(bigint) to authenticated;
grant execute on function public.mark_read() to authenticated;
